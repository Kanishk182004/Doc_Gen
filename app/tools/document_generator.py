import os
from pathlib import Path
from typing import Optional
from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.oxml import OxmlElement, parse_xml
from docx.oxml.ns import nsdecls, qn
from app.schemas import DocumentContent

def set_cell_background(cell, fill_hex: str):
    """Set background color for a table cell."""
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = parse_xml(f'<w:shd {nsdecls("w")} w:fill="{fill_hex}"/>')
    tc_pr.append(shd)

def set_cell_margins(cell, top=100, bottom=100, left=150, right=150):
    """Set inner cell padding in twips (1/20 of a pt)."""
    tc_pr = cell._tc.get_or_add_tcPr()
    tc_mar = parse_xml(
        f'<w:tcMar {nsdecls("w")}>'
        f'<w:top w:w="{top}" w:type="dxa"/>'
        f'<w:bottom w:w="{bottom}" w:type="dxa"/>'
        f'<w:left w:w="{left}" w:type="dxa"/>'
        f'<w:right w:w="{right}" w:type="dxa"/>'
        f'</w:tcMar>'
    )
    tc_pr.append(tc_mar)

def create_docx_file(doc_content: DocumentContent, output_path: Path) -> Path:
    """Generate an executive-ready, polished .docx document."""
    doc = Document()

    # Configure Margins (1 inch all around)
    for section in doc.sections:
        section.top_margin = Inches(1.0)
        section.bottom_margin = Inches(1.0)
        section.left_margin = Inches(1.0)
        section.right_margin = Inches(1.0)
        # Header / footer setup
        footer = section.footer
        f_p = footer.paragraphs[0]
        f_p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        f_run = f_p.add_run(f"{doc_content.document_type} | Autonomous Document Agent")
        f_run.font.size = Pt(8.5)
        f_run.font.color.rgb = RGBColor(128, 128, 128)

    # Document Header / Title
    title_p = doc.add_paragraph()
    title_p.paragraph_format.space_before = Pt(12)
    title_p.paragraph_format.space_after = Pt(4)
    title_run = title_p.add_run(doc_content.title)
    title_run.font.name = "Calibri"
    title_run.font.size = Pt(24)
    title_run.font.bold = True
    title_run.font.color.rgb = RGBColor(31, 78, 121)  # Deep Navy

    # Subtitle
    if doc_content.subtitle:
        sub_p = doc.add_paragraph()
        sub_p.paragraph_format.space_before = Pt(0)
        sub_p.paragraph_format.space_after = Pt(14)
        sub_run = sub_p.add_run(doc_content.subtitle)
        sub_run.font.name = "Calibri"
        sub_run.font.size = Pt(13)
        sub_run.font.italic = True
        sub_run.font.color.rgb = RGBColor(89, 89, 89)

    # Metadata callout box
    meta_table = doc.add_table(rows=1, cols=2)
    meta_table.alignment = WD_TABLE_ALIGNMENT.CENTER
    meta_table.autofit = False
    
    cell_left = meta_table.cell(0, 0)
    cell_left.width = Inches(3.25)
    set_cell_background(cell_left, "F2F4F7")
    set_cell_margins(cell_left, top=120, bottom=120, left=150, right=150)
    p_meta1 = cell_left.paragraphs[0]
    p_meta1.paragraph_format.space_after = Pt(2)
    r1 = p_meta1.add_run(f"Document Type: {doc_content.document_type}\nStatus: Official Draft")
    r1.font.size = Pt(9.5)
    r1.font.color.rgb = RGBColor(50, 50, 50)

    cell_right = meta_table.cell(0, 1)
    cell_right.width = Inches(3.25)
    set_cell_background(cell_right, "F2F4F7")
    set_cell_margins(cell_right, top=120, bottom=120, left=150, right=150)
    p_meta2 = cell_right.paragraphs[0]
    p_meta2.paragraph_format.space_after = Pt(2)
    r2 = p_meta2.add_run("Generated by: Autonomous Document Agent\nReview State: Quality Verified")
    r2.font.size = Pt(9.5)
    r2.font.color.rgb = RGBColor(50, 50, 50)

    doc.add_paragraph().paragraph_format.space_after = Pt(10)

    # Executive Summary
    if doc_content.executive_summary:
        h_exec = doc.add_heading("Executive Summary", level=1)
        h_exec.paragraph_format.space_before = Pt(14)
        h_exec.paragraph_format.space_after = Pt(4)
        p_exec = doc.add_paragraph(doc_content.executive_summary)
        p_exec.paragraph_format.line_spacing = 1.15
        p_exec.paragraph_format.space_after = Pt(12)

    # Sections
    for sec in doc_content.sections:
        h = doc.add_heading(sec.heading, level=sec.level)
        h.paragraph_format.space_before = Pt(14)
        h.paragraph_format.space_after = Pt(4)

        if sec.body:
            p = doc.add_paragraph(sec.body)
            p.paragraph_format.line_spacing = 1.15
            p.paragraph_format.space_after = Pt(6)

        if sec.bullet_points:
            for bp in sec.bullet_points:
                bp_p = doc.add_paragraph(bp, style="List Bullet")
                bp_p.paragraph_format.space_after = Pt(3)
                bp_p.paragraph_format.line_spacing = 1.1

        if sec.table_headers and sec.table_rows:
            t = doc.add_table(rows=len(sec.table_rows) + 1, cols=len(sec.table_headers))
            t.alignment = WD_TABLE_ALIGNMENT.CENTER
            
            # Header Row
            hdr_cells = t.rows[0].cells
            for idx, text in enumerate(sec.table_headers):
                hdr_cells[idx].text = text
                set_cell_background(hdr_cells[idx], "1F4E79")
                set_cell_margins(hdr_cells[idx], top=100, bottom=100, left=120, right=120)
                for prg in hdr_cells[idx].paragraphs:
                    for run in prg.runs:
                        run.font.bold = True
                        run.font.color.rgb = RGBColor(255, 255, 255)
                        run.font.size = Pt(9.5)

            # Data Rows
            for r_idx, row_data in enumerate(sec.table_rows):
                row_cells = t.rows[r_idx + 1].cells
                fill_color = "F9FAFB" if r_idx % 2 == 1 else "FFFFFF"
                for c_idx, cell_value in enumerate(row_data):
                    if c_idx < len(row_cells):
                        row_cells[c_idx].text = str(cell_value)
                        set_cell_background(row_cells[c_idx], fill_color)
                        set_cell_margins(row_cells[c_idx], top=80, bottom=80, left=120, right=120)
                        for prg in row_cells[c_idx].paragraphs:
                            for run in prg.runs:
                                run.font.size = Pt(9)
            
            doc.add_paragraph().paragraph_format.space_after = Pt(6)

    # Assumptions & Boundary Conditions
    if doc_content.assumptions:
        h_assump = doc.add_heading("Assumptions & Operational Constraints", level=1)
        h_assump.paragraph_format.space_before = Pt(14)
        h_assump.paragraph_format.space_after = Pt(4)
        for a in doc_content.assumptions:
            ap = doc.add_paragraph(a, style="List Bullet")
            ap.paragraph_format.space_after = Pt(3)

    # Next Steps / Recommendations
    if doc_content.next_steps:
        h_next = doc.add_heading("Next Steps & Actionable Recommendations", level=1)
        h_next.paragraph_format.space_before = Pt(14)
        h_next.paragraph_format.space_after = Pt(4)
        for idx, step in enumerate(doc_content.next_steps, 1):
            doc.add_paragraph(f"{idx}. {step}")

    # Output directory write
    output_path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(output_path))
    return output_path
